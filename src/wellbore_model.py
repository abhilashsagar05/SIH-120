# ===========================================================================
# §1  Sucker Rod Parameters
# ===========================================================================
@dataclass
class SuckerRodParams:
    """
    Physical constants for the Baghewala Sucker Rod string.
    Defaults to a standard API rod string configuration.
    """
    L_m: float = 2000.0             # m, total depth to pump
    D_rod_m: float = 0.0254         # m, rod diameter (1 inch)
    E_Pa: float = 200e9             # Pa, Young's Modulus for steel
    rho_rod_kg_m3: float = 7850.0   # kg/m³, density of steel
    rho_fluid_kg_m3: float = 962.0  # kg/m³, Baghewala heavy crude density
    c_damping_s: float = 0.5        # 1/s, viscous damping (high due to heavy oil)
    
    A_rod_m2: float = field(init=False)
    a_wave_m_s: float = field(init=False)
    g_eff_m_s2: float = field(init=False)

    def __post_init__(self):
        self.A_rod_m2 = np.pi * (self.D_rod_m / 2.0)**2
        self.a_wave_m_s = np.sqrt(self.E_Pa / self.rho_rod_kg_m3)
        # Effective gravity with buoyancy: g * (1 - rho_fluid/rho_rod)
        self.g_eff_m_s2 = 9.81 * (1.0 - (self.rho_fluid_kg_m3 / self.rho_rod_kg_m3))


# ===========================================================================
# §2  Physics-Informed Neural Network (PINN)
# ===========================================================================
class GibbsWavePINN(nn.Module):
    """
    Feed-forward Neural Network mapping (x, t) -> u(x, t).
    Uses Tanh activations as they are smooth and twice differentiable,
    which is strictly required for the 2nd order Gibbs Wave PDE.
    """
    def __init__(self, layers: list[int] = [2, 64, 64, 64, 64, 1]):
        super().__init__()
        
        modules = []
        for i in range(len(layers) - 2):
            modules.append(nn.Linear(layers[i], layers[i+1]))
            modules.append(nn.Tanh())
            
        modules.append(nn.Linear(layers[-2], layers[-1]))
        self.net = nn.Sequential(*modules)
        
        # Xavier initialization for stable gradients
        self.apply(self._init_weights)

    def _init_weights(self, m):
        if isinstance(m, nn.Linear):
            nn.init.xavier_normal_(m.weight)
            nn.init.constant_(m.bias, 0)

    def forward(self, x: torch.Tensor, t: torch.Tensor) -> torch.Tensor:
        """
        Inputs:
            x: depth tensor [N, 1]
            t: time tensor [N, 1]
        Output:
            u: displacement [N, 1]
        """
        inputs = torch.cat([x, t], dim=1)
        return self.net(inputs)


# ===========================================================================
# §3  Wellbore Model & Training Engine
# ===========================================================================
class WellboreModel:
    """
    Encapsulates the physics constraints, boundary conditions, and training 
    regimen for the SRP PINN.
    """
    def __init__(self, params: Optional[SuckerRodParams] = None):
        self.p = params if params is not None else SuckerRodParams()
        self.pinn = GibbsWavePINN()
        self.optimizer = torch.optim.Adam(self.pinn.parameters(), lr=1e-3)
        
        # Scaling factors for numerical stability in the NN (Normalisation)
        self.x_scale = self.p.L_m
        self.t_scale = 10.0  # Approx 1 cycle duration [s]
        self.u_scale = 3.0   # Approx max stroke length [m]
        self.F_scale = self.p.E_Pa * self.p.A_rod_m2 * (self.u_scale / self.x_scale)
        
        logger.info(
            f"Initialized Wellbore PINN | a={self.p.a_wave_m_s:.1f} m/s | "
            f"g_eff={self.p.g_eff_m_s2:.2f} m/s² | Damping c={self.p.c_damping_s} 1/s"
        )

    def compute_loss(
        self, 
        x_col: torch.Tensor, 
        t_col: torch.Tensor, 
        t_surf: torch.Tensor, 
        u_surf_obs: torch.Tensor, 
        F_surf_obs: torch.Tensor,
        lambda_pde: float = 1.0
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """
        Computes the custom Physics-Embedded Loss Function:
            L_total = L_data + λ * L_PDE
            
        L_data ensures the network matches surface SCADA telemetry.
        L_PDE ensures the displacement field satisfies the elastodynamic wave equation.
        """
        # ---------------------------------------------------------
        # 1. Physics Loss (L_PDE) calculated on collocation points
        # ---------------------------------------------------------
        x_col.requires_grad_(True)
        t_col.requires_grad_(True)
        
        u_pred = self.pinn(x_col / self.x_scale, t_col / self.t_scale) * self.u_scale
        
        # First derivatives: ∂u/∂x, ∂u/∂t
        du_dx = torch.autograd.grad(u_pred, x_col, grad_outputs=torch.ones_like(u_pred), create_graph=True)[0]
        du_dt = torch.autograd.grad(u_pred, t_col, grad_outputs=torch.ones_like(u_pred), create_graph=True)[0]
        
        # Second derivatives: ∂²u/∂x², ∂²u/∂t²
        d2u_dx2 = torch.autograd.grad(du_dx, x_col, grad_outputs=torch.ones_like(du_dx), create_graph=True)[0]
        d2u_dt2 = torch.autograd.grad(du_dt, t_col, grad_outputs=torch.ones_like(du_dt), create_graph=True)[0]
        
        # Gibbs 1D Damped Wave Residual
        # R = ∂²u/∂t² - a²(∂²u/∂x²) + c(∂u/∂t) - g_eff = 0
        residual = d2u_dt2 - (self.p.a_wave_m_s**2) * d2u_dx2 + self.p.c_damping_s * du_dt - self.p.g_eff_m_s2
        loss_pde = torch.mean(residual**2)
        
        # ---------------------------------------------------------
        # 2. Data Loss (L_data) calculated at surface x=0
        # ---------------------------------------------------------
        x_surf = torch.zeros_like(t_surf, requires_grad=True)
        t_surf = t_surf.clone().requires_grad_(True)
        
        u_surf_pred = self.pinn(x_surf / self.x_scale, t_surf / self.t_scale) * self.u_scale
        
        # Load is defined by Hooke's Law: F(t) = E*A * ∂u/∂x(0,t)
        du_dx_surf = torch.autograd.grad(u_surf_pred, x_surf, grad_outputs=torch.ones_like(u_surf_pred), create_graph=True)[0]
        F_surf_pred = self.p.E_Pa * self.p.A_rod_m2 * du_dx_surf
        
        # Mean Squared Errors for Position and Load
        loss_u = torch.mean(((u_surf_pred - u_surf_obs) / self.u_scale)**2)
        loss_F = torch.mean(((F_surf_pred - F_surf_obs) / self.F_scale)**2)
        
        loss_data = loss_u + loss_F
        
        # ---------------------------------------------------------
        # 3. Total Loss
        # ---------------------------------------------------------
        loss_total = loss_data + lambda_pde * loss_pde
        
        return loss_total, loss_data, loss_pde

    def train_step(self, x_col, t_col, t_surf, u_surf_obs, F_surf_obs, lambda_pde=1.0) -> Dict[str, float]:
        self.optimizer.zero_grad()
        loss, loss_data, loss_pde = self.compute_loss(x_col, t_col, t_surf, u_surf_obs, F_surf_obs, lambda_pde)
        loss.backward()
        self.optimizer.step()
        return {
            "loss_total": loss.item(),
            "loss_data": loss_data.item(),
            "loss_pde": loss_pde.item()
        }


