# §5  Module Smoke Test
# ===========================================================================
def _generate_synthetic_surface_data(params: SuckerRodParams, n_points: int = 100) -> Tuple:
    """
    Generates dummy sinusoidal SCADA telemetry for the smoke test.
    (In reality, this comes from data_ingestion.BaghewalaSCADA)
    """
    t = np.linspace(0, 10, n_points)
    omega = 2.0 * np.pi / 10.0
    
    # Simulate surface stroke of 3 meters
    u_surf = 1.5 * (1 - np.cos(omega * t))
    
    # Simulate surface load (approx peak 80 kN, min 20 kN)
    F_surf = 50000.0 + 30000.0 * np.cos(omega * t - 0.2) 
    
    return t, u_surf, F_surf

