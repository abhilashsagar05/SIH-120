# §4  Downhole Dynamometer Card Generation & Rod Float Detection
# ===========================================================================
class DownholeCardGenerator:
    """
    Queries the trained PINN to reconstruct the subsurface stress state and
    dynamometer card at the plunger (x = L).
    """
    def __init__(self, model: WellboreModel):
        self.model = model

    def generate_card(self, t_array: np.ndarray) -> pd.DataFrame:
        """
        Evaluate the PINN at x = L over time t_array to calculate 
        plunger position and load.
        """
        self.model.pinn.eval()
        
        # Prepare tensors
        t_tensor = torch.tensor(t_array, dtype=torch.float32).unsqueeze(1).requires_grad_(True)
        x_tensor = torch.full_like(t_tensor, self.model.p.L_m, requires_grad=True)
        
        # Query PINN
        u_pred = self.model.pinn(x_tensor / self.model.x_scale, t_tensor / self.model.t_scale) * self.model.u_scale
        
        # Compute Load F = EA(du/dx)
        du_dx = torch.autograd.grad(u_pred, x_tensor, grad_outputs=torch.ones_like(u_pred))[0]
        F_pred = self.model.p.E_Pa * self.model.p.A_rod_m2 * du_dx
        
        # Detect Rod Floating: Occurs if downhole load <= 0 
        # (meaning upward viscous drag overcomes rod weight).
        F_array = F_pred.detach().numpy().flatten()
        u_array = u_pred.detach().numpy().flatten()
        is_floating = F_array <= 0.0
        
        df = pd.DataFrame({
            "time_s": t_array,
            "position_m": u_array,
            "load_N": F_array,
            "load_kN": F_array / 1000.0,
            "rod_floating": is_floating
        })
        return df

    def render_card_svg(self, df: pd.DataFrame, title: str = "Downhole Dynamometer Card") -> str:
        """
        Renders the classic Position vs. Load dynamometer card as an SVG string
        for direct dashboard injection. Highlights regions of rod floating.
        """
        fig, ax = plt.subplots(figsize=(8, 5))
        
        # Plot standard card (tension)
        ax.plot(df['position_m'], df['load_kN'], color='#2C3E50', linewidth=2, label='Plunger Load')
        
        # Highlight rod floating regions (compression / zero load)
        floating_df = df[df['rod_floating']]
        if not floating_df.empty:
            ax.scatter(floating_df['position_m'], floating_df['load_kN'], 
                       color='#E74C3C', s=40, zorder=5, label='Rod Floating Hazard')
            
        ax.axhline(0, color='gray', linestyle='--', alpha=0.7)
        ax.set_title(title, fontsize=14, pad=15)
        ax.set_xlabel("Plunger Displacement [m]", fontsize=12)
        ax.set_ylabel("Plunger Load [kN]", fontsize=12)
        ax.grid(True, linestyle=':', alpha=0.6)
        ax.legend(loc='upper right')
        
        # Tidy up layout and save to SVG buffer
        plt.tight_layout()
        buf = io.StringIO()
        fig.savefig(buf, format='svg', bbox_inches='tight')
        plt.close(fig)
        return buf.getvalue()


