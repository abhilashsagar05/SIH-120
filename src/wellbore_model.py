"""
================================================================================
  BAGHEWALA HEAVY OIL FIELD — Well-to-Surface Digital Twin
  Module : src/wellbore_model.py
  Classes: GibbsWavePINN, WellboreModel, DownholeCardGenerator
  Author : Digital Twin Engineering Team (SIH-DS026)
  Version: 1.0.0

  Purpose
  -------
  Simulates the elastodynamics of a deep Sucker Rod Pump (SRP) system using a
  Physics-Informed Neural Network (PINN). The network solves the 1D Damped Wave
  Equation (Gibbs, 1967) strictly from surface SCADA telemetry (polished rod 
  load and displacement).

  By embedding the physical PDE into the loss function, the PINN acts as an
  in-silico sensor, predicting the displacement u(x,t) and internal rod stress
  at any depth x, down to the plunger at x = L.

  1D Damped Wave Equation (Gibbs formulation with gravity):
  ---------------------------------------------------------
      ∂²u/∂t² = a²(∂²u/∂x²) - c(∂u/∂t) + g_eff

  Where:
      u(x,t) : rod displacement [m] (positive downwards)
      a      : wave propagation velocity in steel = √(E/ρ) [m/s]
      c      : viscous damping coefficient of the heavy crude [s⁻¹]
      g_eff  : effective gravity accounting for fluid buoyancy [m/s²]

  Data Boundaries (at x = 0, Surface):
      u(0, t) = u_surf(t)          (Polished Rod Position)
      EA * ∂u/∂x(0, t) = F_surf(t) (Polished Rod Load)

  Output / Downhole Card:
      The downhole plunger dynamometer card is generated by evaluating the PINN
      at x = L to get u(L, t) and F_pump(t) = EA * ∂u/∂x(L, t).
      "Rod Floating" is detected when the upward viscous drag forces the plunger 
      load to drop to zero during the downstroke.
================================================================================
"""

